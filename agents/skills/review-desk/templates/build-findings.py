#!/usr/bin/env python3
"""Build data-findings.js for the finding desk.

Reads <desk>/raw/:
  meta.json    repo, milestone, generated
  issues.json  `gh issue list --json number,title,state,url,labels,body`
  prs.json     `gh pr list --json number,title,isDraft,state,headRefOid,url,body,files`
  checks.json  the analysis: {"order": [n, ...], "items": {"<n>": {"proposed":
               {"verdict", "reason"}, "checks": [{"text", "evidence"}]}}}
               (see ../prompts/finding-verdict.md)

A PR is a candidate for every issue its body closes (`closes #n`). Without
--desk it builds the example beside this file.
"""
import argparse
import json
import re
from pathlib import Path

_AP = argparse.ArgumentParser()
_AP.add_argument('--desk', default=None, help='desk directory holding raw/')
_AP.add_argument('--out', default=None, help='output directory (default: the desk)')
_ARGS = _AP.parse_args()
ROOT = Path(_ARGS.desk).resolve() if _ARGS.desk else Path(__file__).parent
OUT = Path(_ARGS.out).resolve() if _ARGS.out else ROOT
RAW = ROOT / 'raw'

META = json.loads((RAW / 'meta.json').read_text())
issues = {i['number']: i for i in json.loads((RAW / 'issues.json').read_text())}
prs = json.loads((RAW / 'prs.json').read_text())
CHECKS = json.loads((RAW / 'checks.json').read_text())
CASES = {int(n): c for n, c in CHECKS.get('items', {}).items()}
ORDER = CHECKS.get('order') or sorted(issues)

unknown = sorted((set(CASES) | set(ORDER)) - set(issues))
if unknown:
    raise SystemExit(f'checks.json names issues not in issues.json: {unknown}')

closes = {p['number']: sorted({int(m) for m in re.findall(r'(?i)closes\s+#(\d+)', p['body'] or '')})
          for p in prs}


def summary(body):
    """The finding paragraph, without the issue template headings."""
    text = (body or '').replace('\r', '')
    match = re.search(r'\*\*Finding:\*\*\s*(.+?)(?:\n\s*\n\*\*|\Z)', text, re.S)
    chunk = match.group(1) if match else text
    return re.sub(r'\s+', ' ', chunk).strip()[:520]


items = []
for number in ORDER + [n for n in sorted(issues) if n not in ORDER]:
    issue = issues[number]
    case = CASES.get(number, {})
    labels = [l['name'] for l in issue['labels']]
    severity = next((l for l in labels if l in ('critical', 'high', 'moderate', 'minor')), 'minor')
    candidates = [{
        'pr': p['number'],
        'title': p['title'],
        'url': p['url'],
        'isDraft': p['isDraft'],
        'head': p['headRefOid'],
        'files': len(p['files']),
        'closes': closes[p['number']],
    } for p in prs if number in closes[p['number']]]
    items.append({
        'id': f'f{number}',
        'number': number,
        'title': issue['title'],
        'url': issue['url'],
        'severity': severity,
        'labels': labels,
        'state': issue['state'],
        'finding': summary(issue['body']),
        'candidates': candidates,
        # A proposal, never a verdict: the desk keeps `verdict` empty until the
        # human records one, and starts every check unchecked.
        'proposed': case.get('proposed'),
        'verdict': None,
        'checks': [{'id': f'{number}-{i}', 'text': c['text'], 'evidence': c.get('evidence', '')}
                   for i, c in enumerate(case.get('checks', []))],
        'comment': '',
    })

report = {
    'kind': 'findings',
    'repo': META['repo'],
    'milestone': META['milestone'],
    'generated': META['generated'],
    'items': items,
}
(OUT / 'data-findings.js').write_text(
    '// Generated by build-findings.py from raw/{issues,prs,checks}.json.\n'
    '// Checks are reviewer proposals, not verified facts.\n'
    'window.FINDINGS = ' + json.dumps(report, indent=2, ensure_ascii=False) + ';\n')
print(f'{len(items)} findings -> data-findings.js '
      f'({sum(1 for i in items if not i["candidates"])} without a candidate PR)')
