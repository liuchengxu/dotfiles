#!/usr/bin/env python3
"""Build data.js for the thread desk.

Reads <desk>/raw/:
  meta.json      repo, pr, pinnedSha, branchHeadSha, generated
  comments.json  the PR's review comments, as `gh api --paginate --slurp` returns them
  replies.json   optional: the analysis, keyed by root comment id
                 (see ../prompts/thread-reply.md)

Without --desk it builds the example beside this file.
"""
import argparse
import base64
import json
from pathlib import Path

_AP = argparse.ArgumentParser()
_AP.add_argument('--desk', default=None, help='desk directory holding raw/')
_AP.add_argument('--out', default=None, help='output directory (default: the desk)')
_ARGS = _AP.parse_args()
ROOT = Path(_ARGS.desk).resolve() if _ARGS.desk else Path(__file__).parent
OUT = Path(_ARGS.out).resolve() if _ARGS.out else ROOT
RAW = ROOT / 'raw'

meta = json.loads((RAW / 'meta.json').read_text())
rows = json.loads((RAW / 'comments.json').read_text())
if rows and isinstance(rows[0], list):  # --slurp wraps each page in an outer array
    rows = [c for page in rows for c in page]
rows = list({c['id']: c for c in rows}.values())
replies_file = RAW / 'replies.json'
analysis = json.loads(replies_file.read_text()) if replies_file.is_file() else {}
url = f"https://github.com/{meta['repo']}/pull/{meta['pr']}"


def avatar(login):
    """Embed <desk>/avatars/<login>.png, when present, so the page stays offline."""
    path = ROOT / 'avatars' / f'{login}.png'
    if not path.is_file():
        return None
    return 'data:image/png;base64,' + base64.b64encode(path.read_bytes()).decode()


threads = []
for root in rows:
    if root.get('in_reply_to_id'):
        continue
    replies = sorted((r for r in rows if r.get('in_reply_to_id') == root['id']),
                     key=lambda r: r['created_at'])
    a = analysis.get(str(root['id']), {})
    login = root['user']['login']
    threads.append({
        'id': root['id'],
        'path': root['path'],
        'line': root.get('line'),
        'reviewer': login,
        'reviewerAvatar': avatar(login),
        'createdAt': root['created_at'],
        'url': f"{url}#discussion_r{root['id']}",
        'commit': root['commit_id'],
        'body': root['body'],
        'kind': a.get('kind', 'code'),
        'ask': a.get('ask') or root['body'].strip().splitlines()[0][:80],
        'disposition': a.get('decision', ''),
        'draft': a.get('draft', ''),
        # No status: the page starts every claim unchecked, whatever the analysis says.
        'claims': [{'id': f"{root['id']}-{i}", 'text': c['text'], 'evidence': c.get('evidence', '')}
                   for i, c in enumerate(a.get('claims', []))],
        'draftedAt': a.get('draftedAt', meta['branchHeadSha']),
        'replies': [{'user': r['user']['login'], 'avatar': avatar(r['user']['login']),
                     'body': r['body'], 'createdAt': r['created_at']} for r in replies],
        'answerState': 'answered' if replies else 'open',
    })
threads.sort(key=lambda t: (t['answerState'] != 'open', t['createdAt']))

unknown = sorted(set(analysis) - {str(t['id']) for t in threads})
if unknown:
    raise SystemExit(f'replies.json names comments that are not thread roots: {", ".join(unknown)}')

report = {
    'pr': meta['pr'],
    'title': f"PR #{meta['pr']} review replies",
    'sourceUrl': url,
    'pinnedSha': meta['pinnedSha'],
    'branchHeadSha': meta['branchHeadSha'],
    'generated': meta['generated'],
    'threads': threads,
}
(OUT / 'data.js').write_text(
    '// Generated by build.py from raw/comments.json and raw/replies.json.\n'
    'window.REVIEW = ' + json.dumps(report, indent=2, ensure_ascii=False) + ';\n')
print(f'{len(threads)} threads -> data.js '
      f'({sum(1 for t in threads if t["answerState"] == "open")} open)')
