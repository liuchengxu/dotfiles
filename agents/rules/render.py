#!/usr/bin/env python3
"""Render agent rules for this machine. Preview by default; --check or --apply."""
import argparse
import difflib
import hashlib
import os
from pathlib import Path
import shutil
import sys
import tempfile
from datetime import datetime, timezone

TARGETS = {'claude': '.claude/CLAUDE.md', 'codex': '.codex/AGENTS.md', 'pi': '.pi/agent/AGENTS.md'}
RULES = Path(__file__).resolve().parent
HEADER = '<!-- Generated by ~/.dotfiles/agents/rules/render.py. Edit the sources, then preview and apply. sha256:{} -->\n\n'

def render(body):
    return HEADER.format(hashlib.sha256(body).hexdigest()).encode() + body

def is_clean_render(data):
    return render(data.partition(b'\n\n')[2]) == data

def atomic_write(path, data):
    fd, tmp = tempfile.mkstemp(prefix='.' + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, 'wb') as f:
            f.write(data)
        os.replace(tmp, path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='Exit 1 when any file differs from the sources')
    mode.add_argument('--apply', action='store_true', help='Back up, then write the rendered files')
    args = parser.parse_args()
    state = Path.home() / '.local/state/agent-rules'
    machine_file = state / 'machine'
    if not machine_file.is_file():
        sys.exit(f'No machine file. Write this machine\'s name (for example, studio) to {machine_file}.')
    machine = machine_file.read_text().strip()
    overlay = RULES / 'machines' / f'{machine}.md'
    if not overlay.is_file():
        sys.exit(f'No rules for machine {machine!r}: {overlay} is missing.')
    shared = [(RULES / 'common.md').read_bytes(), (RULES / 'environment.md').read_bytes(), overlay.read_bytes()]
    changed, refused = [], []
    for agent, relative in TARGETS.items():
        path = Path.home() / relative
        parts = shared + [(RULES / 'agents' / f'{agent}.md').read_bytes()]
        new = render(b'\n\n'.join(p.strip() for p in parts if p.strip()) + b'\n')
        old = path.read_bytes() if path.is_file() else None
        if path.is_symlink() or (old is not None and not is_clean_render(old)):
            refused.append(path)
        elif old != new:
            changed.append((agent, path, old, new))
    for path in refused:
        print(f'Refused: {path} is a symlink or was edited after rendering. Fold its edits into the sources, then move it aside.')
    if args.check:
        print('Pending: ' + ', '.join(str(p) for _, p, _, _ in changed) if changed else 'Rendered files match the sources.')
        return int(bool(changed or refused))
    if not args.apply:
        for _, path, old, new in changed:
            old_lines = old.decode().splitlines(True) if old else []
            sys.stdout.writelines(difflib.unified_diff(old_lines, new.decode().splitlines(True), str(path), f'{path} (proposed)'))
        if not changed:
            print('Rendered files match the sources.')
        return int(bool(refused))
    if refused:
        return 1
    if not changed:
        print('Rendered files match the sources; nothing written.')
        return 0
    backup = state / 'backups' / datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S.%fZ')
    backup.mkdir(parents=True)
    for agent, path, old, new in changed:
        if old is not None:
            shutil.copy2(path, backup / f'{agent}.md')
        path.parent.mkdir(parents=True, exist_ok=True)
        atomic_write(path, new)
    print(f'Wrote {len(changed)} files. Backups: {backup}')
    return 0

if __name__ == '__main__':
    sys.exit(main())
